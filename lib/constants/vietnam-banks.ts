export function removeVietnameseAccents(str: string): string {
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D')
    .toLowerCase()
}

export function searchBanks(keyword: string): VietnamBank[] {
  if (!keyword || !keyword.trim()) return VIETNAM_BANKS
  const cleanKeyword = removeVietnameseAccents(keyword.trim())
  return VIETNAM_BANKS.filter((b) => {
    const codeMatch = b.code.toLowerCase().includes(cleanKeyword)
    const shortNameMatch = removeVietnameseAccents(b.shortName).includes(cleanKeyword)
    const nameMatch = removeVietnameseAccents(b.name).includes(cleanKeyword)
    const binMatch = b.bin.includes(cleanKeyword)
    return codeMatch || shortNameMatch || nameMatch || binMatch
  })
}

export function getBankInfo(bankCodeOrBin?: string): VietnamBank | undefined {
  if (!bankCodeOrBin) return undefined
  const query = bankCodeOrBin.trim().toUpperCase()
  return VIETNAM_BANKS.find(
    (b) => b.code.toUpperCase() === query || b.shortName.toUpperCase() === query || b.bin === query
  )
}
